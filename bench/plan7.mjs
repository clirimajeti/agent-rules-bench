#!/usr/bin/env node
// The registered analysis of Plan 7 (studies/plan-7.md): n8n's own written rules (prose) against the same rules as
// lint rules with the feedback loop (rules). Writes studies/plan-7-results.md. Seeded, so the same data gives the
// same numbers. It reuses the statistics of Plan 6; the strata are model x task, since there is one project.
//
//   node bench/plan7.mjs [--out file.md]
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadStudy } from './config.mjs';
import { loadResults } from './summarize.mjs';
import { clopperPearson, exactUpper } from './compare.mjs';
import { mean } from './pool.mjs';
import { costRatio, holm, verifyOk, violating } from './plan6.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
export const STUDY = path.join(ROOT, 'studies', 'n8n-conventions', 'study.json');
export const PRIMARY = ['sonnet', 'haiku'];
const ALPHA = 0.05;
const total = (r) => r.taskCost + r.fixCost;

export function load(file = STUDY) {
  const study = loadStudy(file);
  return loadResults(study.resultsDir).map((r) => ({ ...r, study: study.name }));
}

// prose against rules per model x task; x = prose, y = rules (H16 asks whether prose violates more)
export function strata(runs, models) {
  const out = [];
  for (const model of models) {
    for (const task of [...new Set(runs.map((r) => r.task))].sort()) {
      const side = (arm) => runs.filter((r) => r.ok && r.model === model && r.task === task && r.arm === arm);
      const x = side('prose'), y = side('rules');
      if (!x.length || !y.length) continue;
      out.push({ model, task, x, y, n1: x.length, n2: y.length, x1: x.filter((r) => violating(r)).length, x2: y.filter((r) => violating(r)).length });
    }
  }
  return out;
}

const p3 = (p) => (p < 0.001 ? '<0.001' : p.toFixed(3));
const pct = (r) => { const v = Math.round((r - 1) * 100); return v === 0 ? '0%' : `${v > 0 ? '+' : ''}${v}%`; };
const ci95 = (k, n) => { if (!n) return '-'; const [lo, hi] = clopperPearson(k, n); return `${(lo * 100).toFixed(0)}-${(hi * 100).toFixed(0)}%`; };
const frac = (k, n) => `${k}/${n}`;
const sum = (ss, k) => ss.reduce((a, s) => a + s[k], 0);
const rulesOf = (r) => new Set((r.breaksAfterTaskAt ?? []).map((f) => f.ruleId.replace(/^local\//, '')));

export function analyse(runs = load()) {
  const out = ['# Plan 7: results', '', 'Generated by `node bench/plan7.mjs` from the result files. Registered plan: `studies/plan-7.md`.', ''];
  const notOk = runs.filter((r) => !r.ok && PRIMARY.includes(r.model));
  if (notOk.length) out.push(`Runs left out because their session failed: ${notOk.map((r) => `${r.study}/${r.id}`).join(', ')}.`, '');

  const ss = strata(runs, PRIMARY);
  const x1 = sum(ss, 'x1'), n1 = sum(ss, 'n1'), x2 = sum(ss, 'x2'), n2 = sum(ss, 'n2');
  const h16 = exactUpper(ss);
  const h17 = costRatio(ss);
  const h17task = costRatio(ss, (r) => r.taskCost);
  const adj = holm({ H16: h16, H17: h17.p });

  out.push('## Confirmatory: H16 and H17 (Holm, family-wise alpha 0.05)', '');
  out.push('### H16: prose has more violating runs than rules', '');
  out.push(`Pooled: prose ${frac(x1, n1)} (${(100 * x1 / n1).toFixed(1)}%), rules ${frac(x2, n2)} (${(100 * x2 / n2).toFixed(1)}%); risk difference ${(100 * (x1 / n1 - x2 / n2)).toFixed(1)} percentage points; exact conditional CMH, one-sided: p = ${p3(h16)}.`, '');
  out.push('| model | task | prose violating | rules violating | Fisher p (one-sided) |', '|---|---|---|---|---|');
  for (const s of ss) out.push(`| ${s.model} | ${s.task} | ${frac(s.x1, s.n1)} (${ci95(s.x1, s.n1)}) | ${frac(s.x2, s.n2)} (${ci95(s.x2, s.n2)}) | ${p3(exactUpper([s]))} |`);
  out.push('', '### H17: the cost of rules is equivalent to the cost of prose within 10%', '');
  out.push(`- Total cost (task plus review fix), rules / prose: ${pct(h17.point)}; 90% stratified bootstrap interval ${pct(h17.ci[0])} to ${pct(h17.ci[1])}; margin -10% to +10%; TOST p = ${p3(h17.p)}.`);
  out.push(`- Task session only (without the review fix): ${pct(h17task.point)}; 90% interval ${pct(h17task.ci[0])} to ${pct(h17task.ci[1])}.`, '');
  out.push('| hypothesis | p | Holm-adjusted p | holds at 0.05 |', '|---|---|---|---|');
  out.push(`| H16 | ${p3(h16)} | ${p3(adj.H16)} | ${adj.H16 <= ALPHA ? 'yes' : 'no'} |`, `| H17 | ${p3(h17.p)} | ${p3(adj.H17)} | ${adj.H17 <= ALPHA ? 'yes' : 'no'} |`, '');

  // secondary, without a test decision
  const ok = runs.filter((r) => r.ok && PRIMARY.includes(r.model));
  const arm = (a) => ok.filter((r) => r.arm === a);
  const ruleIds = [...new Set(ok.flatMap((r) => [...rulesOf(r)]))].sort();
  out.push('## Secondary (no test decision)', '', '### Violating runs per rule', '', '| rule | prose runs | rules runs |', '|---|---|---|');
  for (const id of ruleIds) out.push(`| ${id} | ${arm('prose').filter((r) => rulesOf(r).has(id)).length} | ${arm('rules').filter((r) => rulesOf(r).has(id)).length} |`);
  out.push('', '### Per arm', '', '| arm | runs | capped | violating | runs left violating at the end | loop catches (runs) | ignored catches (runs) | mean turns | mean total cost | verify passes |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const a of ['prose', 'rules']) {
    const rs = arm(a);
    const v = rs.map((r) => verifyOk(r)).filter((x) => x !== null);
    const pass = v.filter(Boolean).length;
    out.push(`| ${a} | ${rs.length} | ${rs.filter((r) => r.capped).length} | ${rs.filter((r) => violating(r)).length} | ${rs.filter((r) => r.breaksFinal > 0).length} | ${a === 'rules' ? rs.filter((r) => r.hookCatches > 0).length : '-'} | ${a === 'rules' ? rs.filter((r) => r.ignoredCatches > 0).length : '-'} | ${mean(rs.map((r) => r.turns)).toFixed(1)} | $${mean(rs.map(total)).toFixed(3)} | ${v.length ? `${frac(pass, v.length)} (${ci95(pass, v.length)})` : 'not verified'} |`);
  }
  out.push('');
  return out.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const i = process.argv.indexOf('--out');
  const file = i > 0 ? process.argv[i + 1] : path.join(ROOT, 'studies', 'plan-7-results.md');
  fs.writeFileSync(file, analyse());
  console.log(`wrote ${file}`);
}
